// Generates supabase/seed.sql from the same generateSeed() that LocalStore uses, so both stores
// start from identical data. Run: npm run db:seed (tsx is needed to import the TypeScript source).
//
// Rows go into the seed_* snapshot tables, stamped relative to a fixed ANCHOR; the trailing
// `select public._reseed()` (also what reset_demo() runs) copies them into the live tables
// shifted so ANCHOR becomes now(). The output is therefore deterministic.
import { writeFileSync } from "node:fs";
import { generateSeed } from "../src/data/seed.ts";

const ANCHOR = new Date("2026-10-01T09:30:00.000Z"); // 15:00 IST
const OUT = new URL("../supabase/seed.sql", import.meta.url);

const db = generateSeed(ANCHOR);

// Seed ids ("seed-o-1001") become fixed UUIDs; the middle group encodes the kind.
const KIND = { c: "8001", o: "8002", p: "8003", l: "8004" };
const uuid = (seedId) => {
  const m = /^seed-([colp])-(\d+)$/.exec(seedId);
  if (!m) throw new Error(`unexpected seed id ${seedId}`);
  return `00000000-0000-4000-${KIND[m[1]]}-${m[2].padStart(12, "0")}`;
};

const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replaceAll("'", "''")}'`);
const b = (v) => (v === null || v === undefined ? "null" : v ? "true" : "false");
const n = (v) => (v === null || v === undefined ? "null" : String(v));
const js = (v) => (v === null || v === undefined ? "null" : `${q(JSON.stringify(v))}::jsonb`);
const arr = (a) => `array[${a.map(q).join(", ")}]::text[]`;
const ts = (iso) => `${q(iso)}::timestamptz`;

function insert(table, cols, rows) {
  if (rows.length === 0) return "";
  const out = [];
  for (let i = 0; i < rows.length; i += 400) {
    const chunk = rows.slice(i, i + 400).map((r) => `  (${r.join(", ")})`);
    out.push(`insert into public.${table} (${cols.join(", ")}) values\n${chunk.join(",\n")};`);
  }
  return out.join("\n") + "\n";
}

const s = db.settings;
const parts = [
  `-- GENERATED by scripts/gen-seed-sql.mjs from src/data/seed.ts generateSeed(${ANCHOR.toISOString()}). Do not edit.`,
  "-- Run after the migrations (SQL editor). Safe to re-run: it replaces the snapshot and resets the demo.",
  "begin;",
  "truncate public.seed_meta, public.seed_settings, public.seed_menu_categories, public.seed_menu_items, public.seed_item_options,",
  "  public.seed_tables, public.seed_customers, public.seed_coupons, public.seed_orders, public.seed_order_items,",
  "  public.seed_payments, public.seed_loyalty_ledger;",
  insert("seed_meta", ["id", "anchor", "next_code"], [[b(true), ts(ANCHOR.toISOString()), n(db.nextCode)]]),
  insert(
    "seed_settings",
    ["id", "cafe_name", "phone", "whatsapp", "gst_percent", "accepting_orders", "slot_minutes", "tables", "socials", "delivery", "hours", "loyalty"],
    [[b(true), q(s.cafeName), q(s.phone), q(s.whatsapp), n(s.gstPercent), b(s.acceptingOrders), n(s.slotMinutes), n(s.tables), js(s.socials), js(s.delivery), js(s.hours), js(s.loyalty)]],
  ),
  insert("seed_menu_categories", ["id", "name", "sort"], db.categories.map((c) => [q(c.id), q(c.name), n(c.sort)])),
  insert(
    "seed_menu_items",
    ["id", "category_id", "name", "description", "price", "image_url", "is_veg", "is_egg", "tags", "is_available", "nutrition", "sort"],
    db.items.map((i, idx) => [q(i.id), q(i.categoryId), q(i.name), q(i.description), n(i.price), q(i.image), b(i.veg), b(i.egg), arr(i.tags), b(i.available), js(i.nutrition ?? null), n(idx)]),
  ),
  insert(
    "seed_item_options",
    ["id", "item_id", "group_name", "label", "price_delta", "sort"],
    db.items.flatMap((i) => i.options.map((o, idx) => [q(o.id), q(i.id), q(o.group), q(o.label), n(o.priceDelta), n(idx)])),
  ),
  insert("seed_tables", ["number", "label", "active"], Array.from({ length: s.tables }, (_, i) => [n(i + 1), q(`Table ${i + 1}`), b(true)])),
  insert(
    "seed_customers",
    ["id", "phone", "name", "marketing_opt_in", "notes", "tags", "created_at"],
    db.customers.map((c) => [q(uuid(c.id)), q(c.phone), q(c.name), b(c.marketingOptIn), q(c.notes), arr([]), ts(c.createdAt)]),
  ),
  insert(
    "seed_coupons",
    ["code", "type", "value", "min_order", "max_discount", "expires_at", "usage_limit", "used_count", "first_order_only", "active", "created_at"],
    db.coupons.map((c, idx) => [q(c.code), q(c.type), n(c.value), n(c.minOrder), n(c.maxDiscount), c.expiresAt ? ts(c.expiresAt) : "null", n(c.usageLimit), n(c.usedCount), b(c.firstOrderOnly), b(c.active), ts(new Date(ANCHOR.getTime() - 60 * 86400000 + idx * 1000).toISOString())]),
  ),
  insert(
    "seed_orders",
    ["id", "short_code", "customer_id", "customer_name", "phone", "mode", "table_number", "pickup_time", "status", "subtotal", "discount", "loyalty_discount", "points_redeemed", "taxable", "cgst", "sgst", "tax", "total", "online_due", "payment_status", "coupon_code", "idempotency_key", "created_at", "updated_at", "seq"],
    db.orders.map((o, idx) => {
      const bl = o.bill;
      const online = o.payments.filter((p) => p.method === "online").reduce((a, p) => a + p.amount, 0);
      return [q(uuid(o.id)), q(o.code), q(uuid(o.customerId)), q(o.customerName), q(o.phone), q(o.mode), n(o.table), q(o.pickupTime), q(o.status), n(bl.subtotal), n(bl.couponDiscount), n(bl.loyaltyDiscount), n(bl.pointsRedeemed), n(bl.taxable), n(bl.cgst), n(bl.sgst), n(bl.cgst + bl.sgst), n(bl.total), n(online), q(o.paymentStatus), q(o.couponCode), "null", ts(o.createdAt), ts(o.updatedAt), n(idx + 1)];
    }),
  ),
  insert(
    "seed_order_items",
    ["order_id", "line_no", "item_id", "name_snapshot", "unit_price", "options", "qty", "note", "line_total"],
    db.orders.flatMap((o) =>
      o.bill.lines.map((l, idx) => [q(uuid(o.id)), n(idx + 1), q(l.itemId), q(l.name), n(l.unitPrice), js(l.optionIds.map((id, k) => ({ id, label: l.optionLabels[k] }))), n(l.qty), q(l.note ?? null), n(l.lineTotal)]),
    ),
  ),
  insert(
    "seed_payments",
    ["id", "order_id", "method", "channel", "amount", "status", "reference", "created_at", "recorded_by", "seq"],
    db.orders
      .flatMap((o) => o.payments.map((p) => [o, p]))
      .map(([o, p], idx) => [q(uuid(p.id)), q(uuid(o.id)), q(p.method), q(p.channel), n(p.amount), q(p.status), q(p.reference), ts(p.createdAt), "null", n(idx + 1)]),
  ),
  insert(
    "seed_loyalty_ledger",
    ["id", "customer_id", "order_id", "points", "reason", "created_at", "seq"],
    db.ledger.map((l, idx) => [q(uuid(l.id)), q(uuid(l.customerId)), l.orderId ? q(uuid(l.orderId)) : "null", n(l.points), q(l.reason), ts(l.createdAt), n(idx + 1)]),
  ),
  "select public._reseed();",
  "commit;",
  "",
];

writeFileSync(OUT, parts.filter(Boolean).join("\n"));
console.log(`wrote supabase/seed.sql: ${db.orders.length} orders, ${db.customers.length} customers, ${db.items.length} items`);
